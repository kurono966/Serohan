def analyze():
    snapshot = json.loads((ROOT / 'tatoeba-source.json').read_text(encoding='utf-8'))
    sources = {r['id']: r for r in snapshot['sentences']}
    rows = []
    for line in DATA.splitlines():
        sid, codes, translation, literal, issue, missing = line.split('|')
        sid = int(sid)
        codes = list(dict.fromkeys(codes.replace(' ', '')))
        assert all(c in TYPES for c in codes)
        rows.append({**sources[sid], 'source': 'Tatoeba', 'issue_types': codes,
                     'serohan': translation or None, 'literal': literal or None,
                     'fidelity': '部分' if translation else '不能',
                     'issue': issue, 'missing': missing,
                     'rejected_candidate': FAILED_CANDIDATES.get(sid)})
    assert {r['id'] for r in rows} == set(sources) and len(rows) == 60
    return snapshot, rows


